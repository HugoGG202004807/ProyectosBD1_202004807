CREATE TABLE PRODUCTOS_SERVICIOS(
    ID_PRODUCTO_SERVICIO INTEGER PRIMARY KEY,
    TIPO NUMBER(1),
    COSTO NUMBER(12,2),
    DESCRIPCION VARCHAR2(100)
);

CREATE TABLE COMPRAS(
    ID_COMPRA INTEGER PRIMARY KEY,
    FECHA_COMPRA DATE,
    IMPORTE NUMBER(12,2),
    OTROS_DETALLES VARCHAR2(40),
    ID_PRODUCTO_SERVICIO INTEGER,
    ID_CLIENTE INTEGER
);

CREATE TABLE DEPOSITO(
    ID_DEPOSITO INTEGER PRIMARY KEY,
    FECHA_DEPOSITO DATE,
    MONTO NUMBER(12,2),
    OTROS_DETALLES VARCHAR2(40),
    ID_CLIENTE INTEGER
);
CREATE TABLE DEBITO(
    ID_DEBITO INTEGER PRIMARY KEY,
    FECHA_DEBITO DATE,
    MONTO NUMBER(12,2),
    OTROS_DETALLES VARCHAR2(40),
    ID_CLIENTE INTEGER
);

CREATE TABLE TRANSACCION(
    ID_TRANSACCION INTEGER PRIMARY KEY,
    FECHA_TRANSACCION DATE,
    OTROS_DETALLES VARCHAR2(40),
    ID_TIPO_TRANSACCION INTEGER DEFAULT NULL,
    ID_SERVICIO_COMPRA INTEGER DEFAULT NULL,
    ID_SERVICIO_DEPOSITO INTEGER DEFAULT NULL,
    ID_SERVICIO_DEBITO INTEGER,
    ID_CUENTA NUMBER(10)
);


CREATE TABLE TIPO_TRANSACCION(
    ID_TIPO_TRANSACCION INTEGER PRIMARY KEY,
    NOMBRE VARCHAR2(20),
    DESCRIPCION VARCHAR2(40)
);

-- Tabla Historial
CREATE TABLE HISTORIAL (
    ID_HISTORIAL INTEGER GENERATED ALWAYS AS IDENTITY,
    FECHA TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    DESCRIPCION VARCHAR2(100),
    TIPO VARCHAR2(20)
);

