    DESCRIPCION VARCHAR2(50),
    FECHA_APERTURA DATE,
    OTROS_DETALLES VARCHAR2(100),
    ID_TIPO_CUENTA NUMBER(10),
    ID_CLIENTE NUMBER(10)
