FROM DETALLES_ORDENES det
JOIN PRODUCTOS prod ON det.ID_PRODUCTO = prod.ID_PRODUCTO
JOIN CATEGORIAS cat ON prod.ID_CATEGORIA = cat.ID_CATEGORIA
WHERE cat.NOMBRE = 'Deportes'
GROUP BY det.ID_PRODUCTO, prod.NOMBRE
