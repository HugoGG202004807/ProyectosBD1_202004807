SELECT
    v.ID_VENDEDOR,
    v.NOMBRE AS NOMBRE_VENDEDOR,
    SUM(d.CANTIDAD * pr.PRECIO) AS MONTO_TOTAL_VENDIDO
FROM
    VENDEDORES v
JOIN
    DETALLES_ORDENES d ON v.ID_VENDEDOR = d.ID_VENDEDOR
JOIN
    PRODUCTOS pr ON d.ID_PRODUCTO = pr.ID_PRODUCTO
GROUP BY
    v.ID_VENDEDOR,
    v.NOMBRE
ORDER BY
    SUM(d.CANTIDAD) DESC
FETCH FIRST 1 ROW ONLY

