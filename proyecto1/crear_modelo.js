
const script = `

--  TABLA CLIENTES

CREATE TABLE CLIENTES (
    ID_CLIENTE NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100),
    APELLIDO VARCHAR2(100),
    DIRECCION VARCHAR2(200),
    TELEFONO VARCHAR2(20),
    TARJETA VARCHAR2(20),
    EDAD NUMBER(3,0),
    SALARIO NUMBER(10, 2),
    GENERO VARCHAR2(1) CHECK (GENERO IN ('M', 'F')),
    ID_PAIS NUMBER
);


-- TABLA PRODUCTOS

CREATE TABLE PRODUCTOS (
    ID_PRODUCTO NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100),
    PRECIO NUMBER(10,2),
    ID_CATEGORIA NUMBER
);

-- TABLA PAISES

CREATE TABLE PAISES (
    ID_PAIS NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100)
);

-- TABLA CATEGORIAS

CREATE TABLE CATEGORIAS (
    ID_CATEGORIA NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100)
);

-- TABLAS ORDENES_DE_VENTA

CREATE TABLE ORDENES (
    ID_ORDEN NUMBER,
    FECHA_ORDEN VARCHAR2(20),
    ID_CLIENTE NUMBER
);
CREATE TABLE DETALLES_ORDENES ( 
    LINEA_ORDEN NUMBER(10,0),
    ID_VENDEDOR NUMBER,
    ID_PRODUCTO NUMBER,
    CANTIDAD NUMBER(10,0),
    ID_ORDEN NUMBER
);

--TABLA VENDEDORES

CREATE TABLE VENDEDORES (
    ID_VENDEDOR NUMBER PRIMARY KEY,
    NOMBRE VARCHAR2(100),
    ID_PAIS NUMBER
);

    -- ALTERS

ALTER TABLE VENDEDORES
    ADD CONSTRAINT VENDEDORES_PAISES_FK
    FOREIGN KEY (ID_PAIS)
    REFERENCES PAISES(ID_PAIS);

ALTER TABLE CLIENTES
    ADD CONSTRAINT CLIENTES_PAISES_FK
    FOREIGN KEY (ID_PAIS)
    REFERENCES PAISES(ID_PAIS);

ALTER TABLE PRODUCTOS
    ADD CONSTRAINT PRODUCTOS_CATEGORIAS_FK
    FOREIGN KEY (ID_CATEGORIA)
    REFERENCES CATEGORIAS(ID_CATEGORIA);
`;

module.exports = script;


